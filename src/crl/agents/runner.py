"""Hypothesis runner: executes due studies, stores results, flags verdict changes.

Fixes: in F1MEBOT each idea needed its own 20–27 KB installer script, a manual run
and a human reading a text report. Rejected ideas were never re-checked as new
data arrived, so a change in market regime could go unnoticed.
"""
import datetime as dt
import logging
from pathlib import Path

from crl import registry
from crl.config import REPORTS_DIR
from crl.data.store import DataStore
from crl.engine import protocol
from crl.notify import alert

log = logging.getLogger(__name__)


def run(ids: list[str] | None = None, force: bool = False, store: DataStore | None = None,
        today: dt.date | None = None) -> list[dict]:
    today = today or dt.datetime.now(dt.timezone.utc).date()
    store = store or DataStore()
    hyps = registry.load_all()
    changes = []
    for h in hyps:
        if ids and h.id not in ids:
            continue
        if h.get("test_after") and today < dt.date.fromisoformat(str(h["test_after"])):
            continue  # data still accumulating; --force does not override a pre-registered start date
        if not (force and h.get("rerunnable", True) and h.get("status") != "draft") and not registry.is_due(h, today):
            continue
        errs = registry.validate(h)
        if errs:
            changes.append({"id": h.id, "error": "; ".join(errs)})
            continue
        try:
            res = protocol.evaluate(h["spec"], store)
        except (FileNotFoundError, KeyError) as e:
            changes.append({"id": h.id, "error": f"data unavailable: {e}"})
            continue
        prev = registry.store_result(h, res)
        old = prev["verdict"] if prev else None
        log.info("%s: %s (was %s)", h.id, res["verdict"], old)
        changes.append({"id": h.id, "title": h["title"], "verdict": res["verdict"], "previous": old,
                        "summary": res["summary"], "markdown": protocol.to_markdown(h.data, res)})
    write_results_index(registry.load_all())
    if changes:
        write_run_report(changes, today)
    return changes


def write_results_index(hyps, path: Path = REPORTS_DIR / "RESULTS.md") -> None:
    rows = ["# Hypothesis registry", "",
            "Generated by `crl run`. Status reflects the latest verdict; historical F1MEBOT studies "
            "are kept for the record and are not re-run.", "",
            "| id | status | family | title | last run | latest summary |", "|---|---|---|---|---|---|"]
    for h in sorted(hyps, key=lambda x: x.id):
        last = registry.latest_result(h.id)
        summary = last["summary"] if last else ((h.get("history") or [{}])[-1].get("summary", ""))
        rows.append(f"| {h.id} | {h['status']} | {h['family']} | {h['title']} | {h.get('last_run', '—')} | "
                    f"{summary} |")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(rows) + "\n")


def write_run_report(changes: list[dict], today: dt.date) -> Path:
    path = REPORTS_DIR / "runs" / f"{today}.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    parts = [f"# Run {today}", ""]
    for c in changes:
        parts.append(c.get("markdown") or f"### ⚠️ {c['id']}\n\n{c['error']}\n")
    path.write_text("\n".join(parts))
    return path


def main(ids=None, force=False) -> int:
    changes = run(ids, force)
    flips = [c for c in changes if c.get("verdict") and c["verdict"] != c.get("previous")]
    passes = [c for c in changes if c.get("verdict") == "PASS"]
    errors = [c for c in changes if c.get("error")]
    from crl.i18n import VERDICT_WORD_KEYS, sub, t
    from crl.notify import a, lang
    code = lang()

    def word(v):
        return t(code, VERDICT_WORD_KEYS[v]) if v in VERDICT_WORD_KEYS else (v or a("new"))
    lines = [a("flip", id=c["id"], old=word(c.get("previous")), new=word(c["verdict"]),
               title=sub(code, "titles", c["id"], c["title"])) for c in flips]
    lines += [a("passed", id=c["id"]) for c in passes]
    lines += [a("error", id=c["id"], error=c["error"]) for c in errors]
    if lines:
        alert(a("t_runner"), lines)
    log.info("ran %d studies, %d verdict changes, %d errors", len(changes) - len(errors), len(flips), len(errors))
    return 1 if errors else 0
